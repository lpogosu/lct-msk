"""Инфраструктурные лимиты HTTP-слоя тестирования (не продуктовые правила).

Продуктовые пороги (длина теста, стоп, доборы, 14/30/90 дней, детекторы) читаются движками из
config/testing.yaml. Здесь — то, чего в конфиге нет и что относится к защите API и к статистической
осмысленности входов движка (платформа держит свои лимиты так же — в Settings, а не в YAML).
"""

from __future__ import annotations

from app.core.settings import RateRule

# --- Частота запросов (токен-корзина на аккаунт) ---
RL_SESSION_CREATE = RateRule(10, 3600)  # создать сессию: не чаще 10 раз в час
RL_NEXT = RateRule(120, 60)  # GET next (переподключения, опрос состояния)
RL_ANSWER = RateRule(60, 60)  # ответы: живой человек не отвечает чаще раза в секунду
RL_EVENTS = RateRule(120, 60)  # пачки событий фронта
RL_SURVEY = RateRule(60, 60)  # шаги опроса и предпросмотр подсказки
RL_DISPUTE = RateRule(10, 3600)  # «оспорить» флаг
RL_LAB_CALIBRATE = RateRule(5, 300)  # калибровка — тяжёлая операция

# --- Размеры входящих данных ---
MAX_EVENTS_PER_BATCH = 50
MAX_ANSWER_JSON_CHARS = 5000
MAX_DISPUTE_CHARS = 1000

# --- Входы движка из БД ---
# Экспозиция семейства — доля сессий за 30 дней (§2.5). На малом числе сессий доля шумная (1 сессия →
# у всех её семейств экспозиция 1.0), поэтому лимит включается, когда сессий за окно достаточно.
EXPOSURE_WINDOW_DAYS = 30
EXPOSURE_MIN_SESSIONS = 20
# Медиана времени ответа семейства для детектора «быстро и верно» — только при достаточном числе ответов
MEDIAN_RT_MIN_RESPONSES = 5

# --- Пул экземпляров (§2.5: 200 на семейство, догенерация при остатке < 50) ---
POOL_SIZE_DEFAULT = 200
POOL_MIN_FREE = 50
# Клоны для карточки «3 клона рядом» в лаборатории берутся из отдельного диапазона seed: они никогда
# не попадают в боевой пул (его seed секретные, в [2^50, 2^62) — pool.pool_seed), поэтому показ ключа
# методисту не раскрывает ключ ни одного кандидата.
PREVIEW_SEED_BASE = 1_000_000_000
