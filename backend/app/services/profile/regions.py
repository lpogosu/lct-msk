# Названия субъектов в справочнике городов (skills.yaml: cities.*.region) → код
_ALIASES = {
    "Ханты-Мансийский АО": "86",
    "Республика Саха (Якутия)": "14",
}


@lru_cache(maxsize=1)
def _by_name() -> dict[str, str]:
    out = {name.lower(): code for code, name in REGIONS.items()}
    out.update({k.lower(): v for k, v in _ALIASES.items()})
    return out


def region_name(code: str | None) -> str | None:
    return REGIONS.get(code) if code else None


def region_code_by_name(name: str | None) -> str | None:
    return _by_name().get(name.strip().lower()) if name else None


def region_of_city(city_code: str | None) -> str | None:
    """Код субъекта по коду города справочника (moscow → 77)."""
    if not city_code:
        return None
    from app.matching.skills import get_catalog

    city = get_catalog().cities.get(city_code)
    return region_code_by_name(getattr(city, "region", None)) if city is not None else None
